# like uv lock --upgrade, but for cmake :P
# Use branch names for tags in package-sources.cmake; package-lock.cmake pins them to SHAs.
"""Maintain package-sources.cmake (loose refs) and package-lock.cmake (SHAs) for CPM.

  lock-deps.py sync   --build BUILD [--configure] [--lock FILE] [--sources FILE] [--prune]
  lock-deps.py update --build BUILD (--all | NAME ...) [same options]
  lock-deps.py check  [--lock FILE]

sync:   1. add packages from BUILD/cpm-package-lock.cmake that are missing from package-sources.cmake
        2. lock every package that is _then_ in sources but not in the lock
        Existing sources and lock entries are never touched.

update: First runs sync, then updates locks in specified package (or --all) in package-lock.cmake
        to the latest commit on the tip of the branch specified in package-sources.cmake.
        You run this to move to the latest or can change the branch first and use it to switch to,
        for example, develop branch.

check:  clone each locked repo (blobless, bare, temporary) and verify the pinned SHA exists,
        i.e. what a fresh CPM configure needs. Catches force-pushed or deleted commits.

--configure runs `cmake BUILD` with  CPM_INCLUDE_ALL_IN_PACKAGE_LOCK=ON first so the build dir's
                  cpm-package-lock.cmake is current.  It's not necessary if you already configured.
                 dsl_get_repo() already forces CPM_INCLUDE_ALL_IN_PACKAGE_LOCK=ON
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

DECLARE_BLOCK_RE = re.compile(r"^CPMDeclarePackage\(\s*([^\s)]+)(.*?)^\)", re.S | re.M)
STRIP_BLOCK_RE = re.compile(r"(?:^#[^\n]*\n)?^CPMDeclarePackage\(\s*([^\s)]+)(.*?)^\)[ \t]*\n?", re.S | re.M)
GIT_TAG_RE = re.compile(r"(\bGIT_TAG\s+)(\S+)([ \t]*#[^\n]*)?")
COMMIT_SHA_RE = re.compile(r"^[0-9a-f]{40}$")

LOCK_HEADER = "# CPM Package Lock\n# Generated by lock-deps.py from package-sources.cmake. Commit this file.\n\n"
SOURCES_HEADER = "# CPM Package Sources: loose refs (branches, tags). Edit here, then run lock-deps.py.\n\n"


def read_text(path):
    return open(path, encoding="utf-8").read() if os.path.exists(path) else ""


def write_if_changed(path, content):
    if read_text(path) == content:
        return False
    temp_path = path + ".tmp"
    with open(temp_path, "w", encoding="utf-8") as handle:
        handle.write(content)
    os.replace(temp_path, path)
    print(f"wrote {path}")
    return True


def parse_declarations(content):
    """-> ordered {package_name: block_text}. Commented-out entries are ignored."""
    return {match.group(1): match.group(0) for match in DECLARE_BLOCK_RE.finditer(content)}


def extract_field(block, key):
    match = re.search(rf"(?:^|\s){key}\s+(\S+)", block)
    return match.group(1) if match else None


def resolve_ref(repo_url, git_ref):
    if COMMIT_SHA_RE.match(git_ref):
        return git_ref
    git_env = dict(os.environ, GIT_TERMINAL_PROMPT="0")
    result = subprocess.run(
        [
            "git",
            "ls-remote",
            repo_url,
            f"refs/heads/{git_ref}",
            f"refs/tags/{git_ref}",
            f"refs/tags/{git_ref}^{{}}",
        ],
        capture_output=True,
        text=True,
        env=git_env,
    )
    if result.returncode != 0:
        sys.exit(f"git ls-remote failed for {repo_url}: {result.stderr.strip()}")
    refs_by_name = {}
    for line in result.stdout.splitlines():
        commit_sha, full_ref_name = line.split("\t")
        refs_by_name[full_ref_name] = commit_sha
    for candidate in (f"refs/tags/{git_ref}^{{}}", f"refs/heads/{git_ref}", f"refs/tags/{git_ref}"):  # peeled tag first
        if candidate in refs_by_name:
            return refs_by_name[candidate]
    sys.exit(f"cannot resolve '{git_ref}' in {repo_url}")


def lock_block(package_name, source_block, previous_lock_block):
    """Sources block -> lock block with GIT_TAG '<sha> # <ref>'."""
    repo_url = extract_field(source_block, "GIT_REPOSITORY")
    git_ref = extract_field(source_block, "GIT_TAG")
    if not repo_url or not git_ref:
        print(f"  {package_name}: no GIT_REPOSITORY/GIT_TAG, copied as is")
        return source_block
    resolved_sha = resolve_ref(repo_url, git_ref)
    previous_sha = extract_field(previous_lock_block, "GIT_TAG") if previous_lock_block else None
    if resolved_sha != previous_sha:
        print(
            f"  {package_name}: {git_ref} -> {resolved_sha[:12]}"
            + (f" (was {previous_sha[:12]})" if previous_sha else "")
        )
    tag_value = resolved_sha if resolved_sha == git_ref else f"{resolved_sha} # {git_ref}"
    return GIT_TAG_RE.sub(lambda match: match.group(1) + tag_value, source_block, count=1)


def check_lockfile(lock_path):
    lock_entries = parse_declarations(read_text(lock_path))
    if not lock_entries:
        sys.exit(f"no entries in {lock_path}")
    git_env = dict(os.environ, GIT_TERMINAL_PROMPT="0")
    failures = 0
    for package_name, block in lock_entries.items():
        repo_url = extract_field(block, "GIT_REPOSITORY")
        pinned_sha = extract_field(block, "GIT_TAG")
        if not repo_url or not pinned_sha or not COMMIT_SHA_RE.match(pinned_sha):
            print(f"  {package_name}: not a SHA pin, skipped")
            continue
        with tempfile.TemporaryDirectory() as temp_dir:
            clone_result = subprocess.run(
                ["git", "clone", "--bare", "--quiet", "--filter=blob:none", repo_url, temp_dir],
                capture_output=True,
                text=True,
                env=git_env,
            )
            if clone_result.returncode != 0:
                print(f"  {package_name}: clone failed: {clone_result.stderr.strip()}")
                failures += 1
                continue
            commit_exists = (
                    subprocess.run(
                        ["git", "-C", temp_dir, "cat-file", "-e", f"{pinned_sha}^{{commit}}"],
                        env=git_env,
                        stderr=subprocess.DEVNULL,
                    ).returncode
                    == 0
            )
        print(
            f"  {package_name}: {pinned_sha[:12]} "
            + ("ok" if commit_exists else f"MISSING from remote (re-run: update {package_name})")
        )
        failures += not commit_exists
    sys.exit(1 if failures else 0)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("cmd", choices=["sync", "update", "check"])
    parser.add_argument("names", nargs="*", help="update: packages to re-resolve")
    parser.add_argument("--build", help="CMake build dir (sync/update)")
    parser.add_argument("--configure", action="store_true", help="run cmake on the build dir first")
    parser.add_argument("--lock", default="package-lock.cmake")
    parser.add_argument("--sources", help="default: package-sources.cmake beside the lock")
    parser.add_argument("--all", action="store_true", help="update: every package")
    parser.add_argument("--prune", action="store_true", help="drop entries no longer in the CMake project")
    args = parser.parse_intermixed_args()

    if args.cmd == "check":
        check_lockfile(os.path.abspath(args.lock))
    if not args.build:
        sys.exit("--build is required")
    if args.cmd == "sync" and (args.names or args.all):
        sys.exit("sync takes no package names; use 'update' to re-resolve")
    if args.cmd == "update" and not (args.all or args.names):
        sys.exit("update needs --all or package names")

    lock_path = os.path.abspath(args.lock)
    sources_path = os.path.abspath(
        args.sources or os.path.join(os.path.dirname(lock_path), "package-sources.cmake")
    )

    if args.configure:
        cmake_cmd = ["cmake", "-DCPM_INCLUDE_ALL_IN_PACKAGE_LOCK=ON", args.build]
        print("  " + " ".join(cmake_cmd))
        if subprocess.run(cmake_cmd).returncode != 0:
            sys.exit("cmake configure failed")

    build_lock_entries = parse_declarations(read_text(os.path.join(args.build, "cpm-package-lock.cmake")))
    if not build_lock_entries:
        sys.exit(
            "no entries in the build dir's cpm-package-lock.cmake "
            "(configure with CPM_INCLUDE_ALL_IN_PACKAGE_LOCK=ON, or pass --configure)"
        )

    sources_original = read_text(sources_path)
    sources_text = sources_original
    source_entries = parse_declarations(sources_text)
    lock_entries = parse_declarations(read_text(lock_path))

    # 1. merge new packages into sources (existing entries win)
    for package_name, block in build_lock_entries.items():
        if package_name in source_entries:
            continue
        source_entries[package_name] = block
        sources_text = (sources_text or SOURCES_HEADER).rstrip("\n") + f"\n\n# {package_name}\n{block}\n"
        print(f"  {package_name}: added to sources ({extract_field(block, 'GIT_TAG')})")

    # prune packages that left the CMake project
    all_known_packages = list(dict.fromkeys([*source_entries, *lock_entries]))
    for package_name in [name for name in all_known_packages if name not in build_lock_entries]:
        if args.prune:
            print(f"  {package_name}: no longer in project, pruned")
            source_entries.pop(package_name, None)
            lock_entries.pop(package_name, None)
            sources_text = STRIP_BLOCK_RE.sub(
                lambda match: "" if match.group(1) == package_name else match.group(0),
                sources_text,
            )
        else:
            print(f"  {package_name}: not in this configure, keeping (use --prune to drop)")
    sources_text = re.sub(r"\n{3,}", "\n\n", sources_text)

    packages_to_refresh = set(build_lock_entries) if args.all else set(args.names)
    unknown_packages = packages_to_refresh - set(source_entries)
    if unknown_packages:
        sys.exit(f"unknown package '{next(iter(unknown_packages))}'")

    # 2. lock what is loose (in sources, not in lock) plus anything update was asked for
    output_lines = [LOCK_HEADER]
    ordered_packages = dict.fromkeys([*source_entries, *lock_entries])
    for package_name in ordered_packages:
        if package_name in source_entries and (package_name not in lock_entries or package_name in packages_to_refresh):
            block = lock_block(package_name, source_entries[package_name], lock_entries.get(package_name))
        else:
            block = lock_entries[package_name]  # already locked: untouched
        output_lines.append(f"# {package_name}\n{block}\n\n")

    any_change = False
    if sources_text != sources_original:
        any_change |= write_if_changed(sources_path, sources_text)
    any_change |= write_if_changed(lock_path, "".join(output_lines))
    if not any_change:
        print("up to date")


if __name__ == "__main__":
    main()